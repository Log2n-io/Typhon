// Archetypes
//
// Five, and the heterogeneity is the point. The engine's existing spatial workloads all run ONE archetype, which means
// the fence sees one population with one update rate and one durability policy. A game server sees nothing like that:
// its buildings never move and never tick, its creatures move on a slow AI cadence, its players move every tick and are
// the only things anyone queries around, and exactly one of its archetypes is worth a WAL record.
//
// ClusterDurability.Checkpoint on all five is the honest setting rather than a shortcut. A creature's position
// is regenerated by the simulation; writing it to the WAL ten times a second buys a guarantee nobody wants. Inventory
// is the exception and is Versioned, so the WAL is genuinely in the loop.
// ═══════════════════════════════════════════════════════════════════════════════════════════════════════════════════

/// <summary>
/// Everything placed and immobile: city buildings, terminals, shuttleports, point-of-interest props, player houses,
/// factories and harvesters.
/// </summary>
/// <remarks>
/// <para>By far the largest population on a real planet, and the one that costs the fence nothing per tick — provided
/// the fence is told it never moves. This archetype is what <c>SetSpatialBarrierOnly</c> exists for.</para>
/// <para>Factories and harvesters DO tick, on periods of seconds to minutes, but they tick their own counters rather
/// than their position, so the spatial layer never hears from them.</para>
/// </remarks>
[Archetype(1, "Static world objects", ClusterDurability = ClusterDurability.Checkpoint)]
[Replicated]
public partial class WorldObject : Archetype<WorldObject>
{
    [Position]
    public static readonly Comp<StructurePlacement> Bounds = Register<StructurePlacement>();
    public static readonly Comp<Structure> Struct = Register<Structure>();

    /// <summary>The city or point of interest this belongs to: a group set's key, which is why it is not a field on <see cref="Struct"/>.</summary>
    public static readonly Comp<StructureRegion> Region = Register<StructureRegion>();
    public static readonly Comp<StructureRealm> Realm = Register<StructureRealm>();
}

/// <summary>
